package com.example.kidhackbackend.wallet;

import static org.assertj.core.api.Assertions.assertThat;

import com.example.kidhackbackend.admin.finance.dto.AdminUserWalletResponse;
import com.example.kidhackbackend.admin.finance.service.AdminFinanceQueryService;
import com.example.kidhackbackend.global.config.JpaAuditingConfig;
import com.example.kidhackbackend.users.wallet.dto.TxResponse;
import com.example.kidhackbackend.users.wallet.entity.TxType;
import com.example.kidhackbackend.users.wallet.entity.Wallet;
import com.example.kidhackbackend.users.wallet.entity.WalletTransaction;
import com.example.kidhackbackend.users.wallet.repository.WalletRepository;
import com.example.kidhackbackend.users.wallet.repository.WalletTransactionRepository;
import jakarta.persistence.EntityManager;
import java.util.List;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest;
import org.springframework.context.annotation.Import;

/**
 * 지갑 원장 정렬 회귀 — 시드된 큰 id 가 있으면 새 거래가 목록에서 사라지던 결함.
 *
 * <p>{@code wallet_transaction.id} 는 V1 에서 {@code generated by default as identity} 다.
 * {@code BY DEFAULT} 는 명시적 id INSERT 를 허용하면서 <b>시퀀스를 따라 올리지 않는다.</b>
 * 그래서 운영 DB 에 {@code 990001} 같은 큰 id 로 시드된 행이 있으면, 이후 앱이 만드는 거래는
 * 작은 id 를 받아 {@code ORDER BY id DESC} 상위에서 밀려난다 — 잔액은 바뀌었는데 원장은 안 보인다.
 *
 * <p>로컬·CI(H2 + {@code ddl-auto: update})는 시드가 없어 증상이 안 나온다. 그래서 여기서
 * <b>명시적 id 를 native INSERT 로 심어</b> 운영 조건을 만든다.
 */
@DataJpaTest
@Import({AdminFinanceQueryService.class, JpaAuditingConfig.class})
class WalletLedgerOrderTest {

    private static final long OWNER = 990101L;

    @Autowired AdminFinanceQueryService queryService;
    @Autowired WalletRepository walletRepository;
    @Autowired WalletTransactionRepository txRepository;
    @Autowired EntityManager em;

    /** 시드 데이터를 흉내낸다 — 명시적 큰 id + 과거 시각. */
    private void seedTx(long id, long walletId, String type, long amount, long balanceAfter, String day) {
        em.createNativeQuery("""
                        INSERT INTO wallet_transaction
                          (id, wallet_id, type, amount, balance_after, ref_uid, created_at, updated_at)
                        VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7, ?7)""")
                .setParameter(1, id)
                .setParameter(2, walletId)
                .setParameter(3, type)
                .setParameter(4, amount)
                .setParameter(5, balanceAfter)
                .setParameter(6, "seed_" + id)
                .setParameter(7, java.time.LocalDateTime.parse(day + "T10:00:00"))
                .executeUpdate();
    }

    private long walletWithSeededLedger() {
        long walletId = walletRepository.save(new Wallet(OWNER)).getId();
        seedTx(990001L, walletId, "CHARGE", 100_000L, 100_000L, "2026-08-25");
        seedTx(990002L, walletId, "CHARGE", 100_000L, 200_000L, "2026-08-26");
        seedTx(990003L, walletId, "PAYMENT", 12_000L, 188_000L, "2026-08-27");
        seedTx(990004L, walletId, "CHARGE", 100_000L, 288_000L, "2026-08-28");
        seedTx(990005L, walletId, "ADJUST", 0L, 288_000L, "2026-08-29");
        em.flush();
        em.clear();
        return walletId;
    }

    @Test
    void 시드된_큰id가_있어도_새_환불거래가_최근거래_맨앞에_온다() {
        long walletId = walletWithSeededLedger();

        // 앱이 만드는 새 거래 — identity 시퀀스를 따라 작은 id 를 받는다.
        WalletTransaction refund = txRepository.save(
                new WalletTransaction(walletId, TxType.REFUND, 40_000L, 248_000L, "kid_new"));
        assertThat(refund.getId()).isLessThan(990001L); // 전제 확인: 실제로 작은 id 를 받았다

        AdminUserWalletResponse res = queryService.getUserWallet(OWNER);

        assertThat(res.recentTransactions()).isNotEmpty();
        assertThat(res.recentTransactions().get(0).refUid()).isEqualTo("kid_new");
        assertThat(res.recentTransactions().get(0).type()).isEqualTo("REFUND");
    }

    @Test
    void 원장_페이징_조회도_시각_최신순이다() {
        long walletId = walletWithSeededLedger();
        txRepository.save(new WalletTransaction(walletId, TxType.REFUND, 40_000L, 248_000L, "kid_new"));

        List<WalletTransaction> all = txRepository.findByWalletIdRecentFirst(walletId);

        assertThat(all).hasSize(6);
        assertThat(all.get(0).getRefUid()).isEqualTo("kid_new");
        assertThat(all.get(1).getRefUid()).isEqualTo("seed_990005");
    }

    @Test
    void 같은_시각이면_id_내림차순으로_2차정렬한다() {
        long walletId = walletRepository.save(new Wallet(OWNER)).getId();
        seedTx(990001L, walletId, "CHARGE", 1_000L, 1_000L, "2026-08-25");
        seedTx(990002L, walletId, "CHARGE", 1_000L, 2_000L, "2026-08-25");
        seedTx(990003L, walletId, "CHARGE", 1_000L, 3_000L, "2026-08-25");
        em.flush();
        em.clear();

        List<TxResponse> recent = queryService.getUserWallet(OWNER).recentTransactions();

        assertThat(recent).extracting(TxResponse::id)
                .containsExactly(990003L, 990002L, 990001L);
    }
}
