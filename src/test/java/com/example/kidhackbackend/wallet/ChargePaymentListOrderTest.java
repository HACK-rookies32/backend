package com.example.kidhackbackend.wallet;

import static org.assertj.core.api.Assertions.assertThat;

import com.example.kidhackbackend.global.config.JpaAuditingConfig;
import com.example.kidhackbackend.users.qrpay.entity.QrPayment;
import com.example.kidhackbackend.users.qrpay.repository.AdminPaymentProjection;
import com.example.kidhackbackend.users.qrpay.repository.QrPaymentRepository;
import com.example.kidhackbackend.users.wallet.entity.ChargeOrder;
import com.example.kidhackbackend.users.wallet.repository.AdminChargeProjection;
import com.example.kidhackbackend.users.wallet.repository.ChargeOrderRepository;
import jakarta.persistence.EntityManager;
import java.time.LocalDateTime;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.data.jpa.test.autoconfigure.DataJpaTest;
import org.springframework.context.annotation.Import;
import org.springframework.data.domain.Page;
import org.springframework.data.domain.PageRequest;

/**
 * 충전 주문·매장결제 목록 정렬 회귀 — #165 와 같은 결함이 이 두 테이블에도 있었다.
 *
 * <p>{@code charge_order.id}·{@code qr_payment.id} 모두 {@code generated by default as identity} 라
 * 명시적 id 로 시드된 행이 있으면 시퀀스가 따라 올라가지 않는다. 새 주문·결제가 작은 id 를 받아
 * {@code ORDER BY id DESC} 상위에서 밀려난다.
 *
 * <p>운영에 시드가 있다는 근거: 웹이 #165 근거로 보낸 충전 건 id 가 {@code 990006} 이었다.
 *
 * <p>로컬·CI(H2 + {@code ddl-auto: update})는 시드가 없어 증상이 안 난다. 그래서 여기서
 * <b>명시적 id 를 native INSERT 로 심어</b> 운영 조건을 만든다.
 */
@DataJpaTest
@Import(JpaAuditingConfig.class)
class ChargePaymentListOrderTest {

    private static final long OWNER = 990101L;
    private static final long CHILD = 990202L;

    @Autowired ChargeOrderRepository chargeOrderRepository;
    @Autowired QrPaymentRepository qrPaymentRepository;
    @Autowired EntityManager em;

    private void seedCharge(long id, String merchantUid, String day) {
        em.createNativeQuery("""
                        INSERT INTO charge_order
                          (id, merchant_uid, owner_id, amount, status, created_at, updated_at)
                        VALUES (?1, ?2, ?3, 100000, 'PAID', ?4, ?4)""")
                .setParameter(1, id)
                .setParameter(2, merchantUid)
                .setParameter(3, OWNER)
                .setParameter(4, LocalDateTime.parse(day + "T10:00:00"))
                .executeUpdate();
    }

    private void seedPayment(long id, String qrToken, String day) {
        em.createNativeQuery("""
                        INSERT INTO qr_payment
                          (id, qr_token, child_id, amount, status, store_name,
                           expires_at, paid_at, created_at, updated_at)
                        VALUES (?1, ?2, ?3, 3000, 'PAID', 'seed-store', ?4, ?4, ?4, ?4)""")
                .setParameter(1, id)
                .setParameter(2, qrToken)
                .setParameter(3, CHILD)
                .setParameter(4, LocalDateTime.parse(day + "T10:00:00"))
                .executeUpdate();
    }

    private void seedCharges() {
        seedCharge(990001L, "kid_seed1", "2026-08-25");
        seedCharge(990004L, "kid_seed4", "2026-08-28");
        seedCharge(990006L, "kid_seed6", "2026-08-29");
        em.flush();
        em.clear();
    }

    private void seedPayments() {
        seedPayment(990001L, "qr_seed1", "2026-08-25");
        seedPayment(990004L, "qr_seed4", "2026-08-28");
        seedPayment(990006L, "qr_seed6", "2026-08-29");
        em.flush();
        em.clear();
    }

    // ---------- charge_order ----------

    @Test
    void 충전내역_시드된_큰id가_있어도_새_주문이_맨앞에_온다() {
        seedCharges();
        ChargeOrder fresh = chargeOrderRepository.save(new ChargeOrder("kid_new", OWNER, 40_000L));
        assertThat(fresh.getId()).isLessThan(990001L); // 전제: 실제로 작은 id 를 받았다

        Page<ChargeOrder> page =
                chargeOrderRepository.findByOwnerIdRecentFirst(OWNER, PageRequest.of(0, 3));

        assertThat(page.getContent().get(0).getMerchantUid()).isEqualTo("kid_new");
    }

    @Test
    void 관리자_충전목록도_새_주문이_맨앞에_온다() {
        seedCharges();
        chargeOrderRepository.save(new ChargeOrder("kid_new", OWNER, 40_000L));
        em.flush();
        em.clear();

        Page<AdminChargeProjection> page =
                chargeOrderRepository.adminSearchCharges(null, null, null, PageRequest.of(0, 3));

        assertThat(page.getContent().get(0).getMerchantUid()).isEqualTo("kid_new");
    }

    // ---------- qr_payment ----------

    @Test
    void 자녀결제내역_시드된_큰id가_있어도_새_결제가_맨앞에_온다() {
        seedPayments();
        QrPayment fresh = new QrPayment("qr_new", CHILD, LocalDateTime.now().plusMinutes(5));
        fresh.markPaid(3_000L, "새매장", 1L, LocalDateTime.now());
        qrPaymentRepository.save(fresh);
        em.flush();
        em.clear();

        Page<QrPayment> page = qrPaymentRepository
                .findByChildIdAndPaidAtIsNotNullRecentFirst(CHILD, PageRequest.of(0, 3));

        assertThat(page.getContent().get(0).getQrToken()).isEqualTo("qr_new");
    }

    @Test
    void 관리자_매장결제목록도_새_결제가_맨앞에_온다() {
        seedPayments();
        QrPayment fresh = new QrPayment("qr_new", CHILD, LocalDateTime.now().plusMinutes(5));
        fresh.markPaid(3_000L, "새매장", 1L, LocalDateTime.now());
        qrPaymentRepository.save(fresh);
        em.flush();
        em.clear();

        Page<AdminPaymentProjection> page = qrPaymentRepository
                .adminSearchPayments(null, null, null, null, PageRequest.of(0, 3));

        assertThat(page.getContent().get(0).getStoreName()).isEqualTo("새매장");
    }
}
