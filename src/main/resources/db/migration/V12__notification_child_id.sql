-- ==================================================================
-- V12 : notification 에 child_id 추가 — 알림이 "어느 자녀에 대한 것인지".
--
-- 배경
--   recipient_id 는 알림을 "받는 사람"이지 대상 자녀가 아니다. message 에도
--   자녀 이름이 없어("'학원'에 진입했습니다.") 본문으로 추정할 수도 없다.
--   그래서 자녀를 둘 이상 둔 보호자는 목록에서 어느 자녀 건지 구분할 수 없었다.
--   모바일 대시보드는 자녀를 골라 그 자녀 알림만 보여 주는 화면이라 필터가 필요하다.
--
--   -> child_id 를 두고, 자녀 맥락이 있는 알림은 발행 시 채운다.
--
-- NULL 을 허용하는 이유
--   (1) 자녀 맥락이 없는 알림이 있다 — 1:1 문의 답변, 관리자 전체 발송.
--   (2) 이 컬럼이 생기기 전에 쌓인 행은 값을 알 수 없다. 소급 백필은 하지 않는다
--       (message 로 자녀를 역추적할 수 없다). 앱은 null 을 "자녀 미지정"으로 다룬다.
--
-- FK 를 걸지 않는 이유
--   notification 은 여러 도메인이 쓰는 공통 테이블이고, member 가 소프트 삭제되어도
--   알림 이력은 남아야 한다. 기존 recipient_id 도 같은 이유로 FK 가 없다.
--
-- 로컬/CI 는 H2 + ddl-auto 라 이 파일을 타지 않는다. 운영(Oracle 19)만 실행된다.
-- ⚠️ V1~V11 은 이미 적용 이력이 있으므로 수정하지 않는다. 적용 후 이 파일도 고치지 말 것.
-- ==================================================================

ALTER TABLE notification ADD (child_id NUMBER(19));

-- 자녀별 목록 조회용. 기존 idx_notification_recipient 는 자녀 조건이 없어
-- 자녀를 고른 화면에서는 수신자 전체를 훑고 필터링하게 된다.
CREATE INDEX idx_notification_child ON notification (recipient_id, child_id, created_at);
