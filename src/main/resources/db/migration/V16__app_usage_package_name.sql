-- V16 : 사용량 집계를 앱 이름 대신 패키지명으로 묶기 위한 컬럼 추가.
--
-- 배경
--   groupBy=APP 집계가 app_name 문자열 기준이라, 같은 앱이 기기 언어에 따라
--   「카메라」와 「Camera」로 따로 잡혔다. 부모 화면의 「많이 사용한 앱」 순위가
--   실제와 어긋난다.
--
-- nullable 인 이유
--   이 컬럼이 생기기 전에 쌓인 행에는 값이 없고, 구버전 자녀 앱도 한동안 보내지
--   않는다. 값이 없는 행은 서비스가 app_name 으로 묶는다(AppUsage.groupingKey).
--   백필하지 않는다 — 옛 행의 패키지명을 알 길이 없고, 사용량은 1주일 롤링
--   삭제라 곧 사라진다.
--
-- 로컬/CI 는 H2 + ddl-auto 라 이 파일을 타지 않는다. 운영(Oracle 19)만 실행된다.
-- ⚠️ 적용 후에는 이 파일을 고치지 말 것.
-- ==================================================================

ALTER TABLE app_usage ADD (package_name VARCHAR2(255));
