-- V18 : 전자금융 별도 비밀번호(계좌비밀번호) + 변경 이력. 역할표 추가 — 전자금융 거래 보안(#193).
--
-- 로그인 비밀번호와 분리된 거래용 비밀번호 체계. 거래 승인·변경 시 본인확인에 쓴다.
--
-- ⚠️ [VULN-EFIN-5] account_password.password_hash 는 salt 없는 MD5(6자리라 즉시 역산).
-- ⚠️ [VULN-EFIN-6] account_password_history.password 는 평문(재사용 대조용) → DB 탈취 시 과거 비번 전량 노출.
--
-- V1~V17 과 마찬가지로 운영 Oracle 에서만 실행된다. 로컬/CI(H2)는 ddl-auto 가 만든다.
-- 한 번 적용된 뒤에는 이 파일을 고치지 말 것(체크섬 어긋나면 앱이 뜨지 않음 — 고칠 땐 다음 번호로).
-- ==================================================================

create table account_password (
    id number(19,0) generated by default as identity,
    member_id number(19,0) not null,
    password_hash varchar2(255 char) not null,   -- [VULN-EFIN-5] salt 없는 MD5
    created_at timestamp(9),
    updated_at timestamp(9),
    primary key (id),
    constraint uq_account_password_member unique (member_id)
);

create table account_password_history (
    id number(19,0) generated by default as identity,
    member_id number(19,0) not null,
    password varchar2(255 char) not null,        -- [VULN-EFIN-6] 평문 이력
    created_at timestamp(9),
    updated_at timestamp(9),
    primary key (id)
);

create index idx_acct_pw_hist_member on account_password_history (member_id);