-- V23 : 첨부 실물을 DB(BLOB)에 담는 db_file 테이블.
--
-- 문의 첨부·프로필 이미지를 S3 대신 DB 에 저장하도록 바꾼다. WAS 2 대(로드밸런서 뒤)
-- 구성에서 로컬 디스크 저장은 인스턴스 간 공유가 안 돼 다운로드가 절반쯤 깨지므로,
-- 두 WAS 가 공유하는 유일한 저장소인 DB(RDS)에 바이트를 담는다.
--
-- ⚠️ content_type/original_filename 은 클라이언트 값을 그대로 저장한다([VULN-10] 계열).
-- ⚠️ Oracle 예약어(size/date/number 등)를 컬럼명으로 쓰지 않는다 → file_size / file_data.
--
-- V1~V9 와 마찬가지로 운영 Oracle 에서만 실행된다. 로컬/CI(H2)는 ddl-auto 가 만든다.
-- 한 번 적용된 뒤에는 고치지 말 것(체크섬). 고칠 땐 다음 버전(V24+)으로.
-- ==================================================================

create table db_file (
    id number(19,0) generated by default as identity,
    category varchar2(32 char) not null,
    file_data blob not null,
    content_type varchar2(255 char),
    original_filename varchar2(1024 char),
    file_size number(19,0),
    created_at timestamp(9),
    updated_at timestamp(9),
    primary key (id)
);
