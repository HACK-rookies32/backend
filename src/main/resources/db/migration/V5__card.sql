-- V5 : 루키즈페이 카드(결제수단) 테이블. 역할표 추가요청 — 카드 CRD(안전 버전).
--
-- 1인당 카드 여러 개. 민감정보는 저장 시 AES-256-GCM 필드암호화(Base64)로 보관하므로
-- 평문 길이(16자리 등)보다 길어진다 → 여유 있게 varchar2(512).
--
-- ⚠️ CVC 컬럼은 두지 않는다. 서버는 복호만 하고 저장하지 않는다(PCI-DSS, 코드 레벨 강제).
-- ⚠️ Oracle 예약어(number/date 등)를 컬럼명으로 쓰지 않는다.
--   (OracleReservedWordColumnTest 가 이 규칙을 검증한다)
--
-- V1~V4 와 마찬가지로 운영 Oracle 에서만 실행된다. 로컬/CI(H2)는 ddl-auto 가 만든다.
-- 한 번 적용된 뒤에는 이 파일을 고치지 말 것 — 체크섬이 어긋나면 앱이 뜨지 않는다(고칠 땐 V6).
-- ==================================================================

create table card (
    id number(19,0) generated by default as identity,
    owner_id number(19,0) not null,
    card_number varchar2(512 char) not null,      -- 암호화 저장(Base64)
    expiry varchar2(255 char) not null,           -- MM/YY (민감도 낮아 평문)
    password_front varchar2(512 char) not null,   -- 앞 2자리, 암호화 저장
    birth_date varchar2(512 char) not null,        -- YYMMDD, 암호화 저장
    owner_name varchar2(512 char) not null,        -- 실명, 암호화 저장
    created_at timestamp(9),
    updated_at timestamp(9),
    primary key (id)
);

-- 본인 카드 목록 조회(owner_id 최신순)가 기본 접근 패턴이라 인덱스를 둔다.
create index idx_card_owner on card (owner_id);
