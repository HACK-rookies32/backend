create table identity_verification (
    id number(19,0) generated by default as identity,
    member_id number(19,0) not null,
    name varchar2(255 char) not null,
    birth_date date not null,
    id_type varchar2(32 char) not null,          -- RESIDENT / DRIVER
    verified number(1,0) not null,
    verified_at timestamp(9),
    created_at timestamp(9),
    updated_at timestamp(9),
    primary key (id)
);

create index idx_identity_member on identity_verification (member_id);