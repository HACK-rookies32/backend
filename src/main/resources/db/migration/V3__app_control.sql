-- ==================================================================
-- V3 : 앱 통제(#110) 테이블 두 개.
--
-- installed_app     : 자녀 기기에 설치된 앱 목록. 동기화 때마다 갱신된다.
-- app_control_rule  : 그중 부모가 통제 대상으로 지정한 앱과 일일 사용 한도.
--
-- 두 테이블 모두 (child_id, package_name) 이 유일하다. 같은 기기에 같은 패키지가
-- 두 번 들어올 수 없고, 동기화가 upsert 로 동작하는 근거가 된다.
--
-- ⚠️ 왜 V3 가 뒤늦게 생겼나
--   V1 은 #110 이전 스키마를 옮긴 것이고, V2 는 감사 로그만 다뤘다. 그 사이 #110 이
--   엔티티 두 개를 추가했는데 마이그레이션이 함께 오지 않아, 운영에서
--   ddl-auto: validate 가 "missing table [app_control_rule]" 로 기동을 거부했다.
--   로컬/CI 는 H2 + ddl-auto 라 엔티티만 있으면 테이블이 생겨 드러나지 않는다.
--
-- 한 번 적용된 뒤에는 이 파일을 고치지 말 것 — 체크섬이 어긋나면 앱이 뜨지 않는다.
-- ==================================================================

create table installed_app (
    id number(19,0) generated by default as identity,
    child_id number(19,0) not null,
    package_name varchar2(255 char) not null,
    app_name varchar2(255 char) not null,
    created_at timestamp(9),
    updated_at timestamp(9),
    primary key (id),
    constraint uk_installed_app_child_pkg unique (child_id, package_name)
);

create table app_control_rule (
    id number(19,0) generated by default as identity,
    child_id number(19,0) not null,
    package_name varchar2(255 char) not null,
    app_name varchar2(255 char) not null,
    daily_limit_minutes number(10,0) not null,
    enabled number(1,0) not null check ((enabled in (0,1))),
    created_at timestamp(9),
    updated_at timestamp(9),
    primary key (id),
    constraint uk_app_control_rule_child_pkg unique (child_id, package_name)
);

-- 조회는 "자녀 한 명의 목록 전체" 가 기본이라 child_id 단독 인덱스를 둔다.
-- 위 UNIQUE 가 만드는 인덱스는 (child_id, package_name) 이라 컬럼 목록이 달라
-- ORA-01408(중복 인덱스)에 걸리지 않는다.
create index idx_installed_app_child on installed_app (child_id);
create index idx_app_control_rule_child on app_control_rule (child_id);