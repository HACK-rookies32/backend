-- ==================================================================
-- V7 : PG 웹훅 수신 기록 테이블 + charge_order.status 제약 갱신.
--
-- (1) #134 가 PgWebhookEvent 엔티티를 추가했지만 마이그레이션이 빠졌다.
--     운영은 ddl-auto=validate 라 "missing table [pg_webhook_event]" 로
--     SessionFactory 생성이 실패하고 컨테이너가 부팅에 실패한다.
--     (로컬/CI 는 H2 + ddl-auto 라 티가 나지 않는다 — #118 과 같은 유형)
--
-- (2) 같은 커밋이 ChargeStatus 에 FAILED 를 추가했다. V1 의 check 제약은
--     ('READY','PAID','CANCELLED') 만 허용한다. validate 는 check 제약을
--     보지 않으므로 앱은 뜨지만, 웹훅이 실패를 통지하는 순간 ORA-02290 이 난다.
--     REFUNDED / EXPIRED 도 같은 이유로 이미 넣을 수 없는 상태였다 —
--     여기서 함께 정리한다. (V6 과 같은 처리 방식)
--
-- ⚠️ V1~V6 파일은 이미 적용된 이력이 있으므로 절대 수정하지 않는다
--    (체크섬이 어긋나면 앱이 뜨지 않는다).
-- ==================================================================

create table pg_webhook_event (
    id number(19,0) generated by default as identity,
    merchant_uid varchar2(255 char),                  -- 파싱 실패 시 null
    status varchar2(255 char),                        -- PG 가 통지한 상태 문자열
    paid_amount number(19,0) not null,
    signature_provided number(1,0) not null check ((signature_provided in (0,1))),
    outcome varchar2(255 char) not null,
    created_at timestamp(9),
    updated_at timestamp(9),
    primary key (id)
);

-- 엔티티의 @Index(name="idx_pg_webhook_merchant", columnList="merchantUid,createdAt") 와 동일.
-- 결제 분쟁·재전송 추적이 "주문번호로 최신순" 조회라 이 순서로 둔다.
create index idx_pg_webhook_merchant on pg_webhook_event (merchant_uid, created_at);

-- ------------------------------------------------------------------
-- charge_order.status : V1 에서 인라인 check 로 만들어져 이름이 SYS_Cxxxxxx 다.
-- 이름으로 지목할 수 없으므로 동적으로 찾아 떨어뜨린다 (V6 과 동일한 방식).
-- ------------------------------------------------------------------
declare
    v_name user_constraints.constraint_name%type;
begin
    select constraint_name into v_name
    from user_constraints
    where table_name = 'CHARGE_ORDER'
      and constraint_type = 'C'
      and search_condition_vc like '%STATUS%'
      and rownum = 1;

    execute immediate 'alter table charge_order drop constraint ' || v_name;
exception
    when no_data_found then
        null;   -- 제약이 없으면(이미 정리됨) 그냥 진행한다.
end;
/

alter table charge_order add constraint ck_charge_order_status
    check (status in ('READY','PAID','FAILED','REFUNDED','CANCELLED','EXPIRED'));
