-- V15 : wallet_transaction 에 사유(memo) 컬럼 추가.
--
-- 웹 요청(2026-08-31, docx/추가수정.txt 6번). 충전 취소 사유를 지갑 원장에서도 볼 수 있어야 한다.
--
-- ⚠️ 왜 refUid 를 재사용하지 않는가
--   refUid 는 기계가 읽는 참조 키다 — CHARGE·REFUND=merchantUid, PAYMENT 계열=qrToken.
--   프론트가 kid_ 접두사로 '충전 환불' 을 식별하는 것이 #131 확정 규약이라 여기에 사유를 넣으면 깨진다.
--   실제로 ADJUST 만 이 규약을 어기고 사유 문자열을 refUid 에 넣고 있었다(라이브 확인).
--   그 건은 memo 로 옮기되, 웹이 refUid 를 읽고 있을 수 있어 당분간 양쪽에 모두 채운다.
--
-- ⚠️ V15 는 origin/main 의 마이그레이션 목록을 확인하고 딴 번호다(V14 까지 소진).
--    이 프로젝트에서 번호 충돌이 두 번 났다 — 푸시 직전에 한 번 더 확인할 것.
-- ⚠️ 이미 적용된 V1~V14 는 절대 수정하지 않는다 — 체크섬이 어긋나면 앱이 뜨지 않는다.
--
-- 로컬·CI 는 H2 + ddl-auto:update 라 엔티티만 고쳐도 증상이 없다. 운영은 Oracle + Flyway +
-- ddl-auto:validate 라 이 파일이 없으면 컬럼 부재로 기동이 실패한다.
-- ==================================================================

-- nullable 이다. 충전 취소(관리자)·잔액 조정만 채우고, 그 외 유형과 배포 이전 거래는 null 이다.
-- 길이 255 는 엔티티 기본값과 맞춘다(사유 원본은 charge_order.refund_reason(500)·
-- admin_audit_log.description(500) 에 그대로 남으므로 여기서 잘려도 유실이 아니다).
alter table wallet_transaction add memo varchar2(255 char);
