-- ==================================================================
-- V2 : 관리자 활동 이력(감사로그) 테이블.
--
-- admin 패키지의 조회(GET)를 제외한 모든 엔드포인트가 성공할 때마다 한 줄씩 쌓인다.
-- 추가만 되고 수정·삭제되지 않으므로 updated_at 은 두지 않는다.
--
-- ⚠️ 테이블/컬럼 이름 주의 : Oracle 예약어 AUDIT 를 피해 admin_audit_log 로 둔다.
--   (OracleReservedWordColumnTest 가 이 규칙을 지킨다)
--
-- V1 과 마찬가지로 운영 Oracle 에서만 실행된다. 로컬/CI(H2)는 ddl-auto 가 만든다.
-- 한 번 적용된 뒤에는 이 파일을 고치지 말 것 — 체크섬이 어긋나면 앱이 뜨지 않는다.
-- ==================================================================

create table admin_audit_log (
    id number(19,0) generated by default as identity,
    admin_id number(19,0) not null,
    target_id number(19,0),
    occurred_at timestamp(9) not null,
    admin_login_id varchar2(255 char) not null,
    activity_type varchar2(255 char) not null check ((activity_type in (
        'ADMIN_LOGIN','MEMBER_UPDATE','MEMBER_DELETE','MEMBER_ROLE_UPDATE','MEMBER_BAN',
        'POST_DELETE','WALLET_BALANCE_ADJUST','PAYMENT_REFUND',
        'INQUIRY_ANSWER_CREATE','INQUIRY_ANSWER_UPDATE','INQUIRY_ANSWER_DELETE',
        'NOTICE_CREATE','NOTICE_UPDATE','NOTICE_DELETE',
        'NOTIFICATION_BROADCAST','HARMFUL_KEYWORD_ADD','HARMFUL_KEYWORD_DELETE'))),
    target_type varchar2(255 char) not null check ((target_type in (
        'MEMBER','WALLET','POST','PAYMENT','INQUIRY','NOTICE','NOTIFICATION','HARMFUL_KEYWORD'))),
    primary key (id)
);

-- 기본 조회가 "발생일시 내림차순 + 기간 필터" 라 정렬/범위 조건을 이 인덱스가 받는다.
create index idx_admin_audit_log_occurred on admin_audit_log (occurred_at);
-- 관리자 로그인 ID 부분 일치 검색용 보조 인덱스(선행 와일드카드라 풀스캔이 될 수 있어 보조 목적).
create index idx_admin_audit_log_admin on admin_audit_log (admin_login_id);
