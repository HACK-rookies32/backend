-- V18 : 전자금융 결제 비밀번호 + 변경 이력. 역할표 추가 — 전자금융 거래 보안(#193).
--
-- 로그인 비밀번호와 분리된 결제용 4자리 PIN. 접근매체(카드) 발급 시 최초 설정하고, 결제 승인·변경 시 본인확인에 쓴다.
--
-- ⚠️ [VULN-EFIN-5] payment_password.password_hash 는 salt 없는 MD5(4자리라 즉시 역산).
-- ⚠️ [VULN-EFIN-6] payment_password_history.password 는 평문(재사용 대조용) → DB 탈취 시 과거 비번 전량 노출.
--
-- V1~V17 과 마찬가지로 운영 Oracle 에서만 실행된다. 로컬/CI(H2)는 ddl-auto 가 만든다.
-- (이 기능은 미배포 상태라 최초부터 payment_password 네이밍으로 둔다. 이미 account_password 로 적용됐다면 rename 마이그레이션을 별도로 추가할 것.)
-- 한 번 적용된 뒤에는 이 파일을 고치지 말 것(체크섬 어긋나면 앱이 뜨지 않음 — 고칠 땐 다음 번호로).
-- ==================================================================

create table payment_password (
    id number(19,0) generated by default as identity,
    member_id number(19,0) not null,
    password_hash varchar2(255 char) not null,   -- [VULN-EFIN-5] salt 없는 MD5
    created_at timestamp(9),
    updated_at timestamp(9),
    primary key (id),
    constraint uq_payment_password_member unique (member_id)
);

create table payment_password_history (
    id number(19,0) generated by default as identity,
    member_id number(19,0) not null,
    password varchar2(255 char) not null,        -- [VULN-EFIN-6] 평문 이력
    created_at timestamp(9),
    updated_at timestamp(9),
    primary key (id)
);

create index idx_pay_pw_hist_member on payment_password_history (member_id);
