-- V18 : member 에 tokens_valid_after 컬럼 추가 — 자녀 강제 로그아웃의 access 토큰 무효화(#202).
--
-- 배경
--   자녀 강제 로그아웃(POST /api/children/{childId}/logout)이 refresh 토큰만 지우고
--   access 토큰(JWT)은 만료(1시간) 전까지 살아 있어, 자녀 기기가 계속 통신했다.
--   JWT 는 무상태라 발급분을 되돌릴 수 없어, 멤버별 "무효화 기준시각"을 두고
--   공유 JWT 필터가 iat < tokens_valid_after 인 토큰을 거부한다.
--
-- NULL 을 허용하는 이유
--   (1) 강제 로그아웃된 적 없는 계정은 제한이 없다(=null).
--   (2) 이 컬럼 도입 이전 계정은 값이 없다. 앱은 null 을 "제한 없음"으로 다룬다.
--   부모/관리자 세션·일반 로그아웃은 이 값을 세팅하지 않으므로 항상 null 이다
--   (의도된 무상태 취약점 유지 — VULN-LOC-2/VULN-5).
--
-- 로컬/CI 는 H2 + ddl-auto:update 라 엔티티만 고쳐도 컬럼이 생긴다. 운영은 Oracle + Flyway +
-- ddl-auto:validate 라 이 파일이 없으면 컬럼 부재로 기동이 실패한다.
-- ⚠️ V18 은 origin/main 의 마이그레이션 목록(V17 까지 소진)을 확인하고 딴 번호다.
--    푸시 직전에 번호 충돌을 한 번 더 확인할 것. 적용된 V1~V17 은 절대 수정하지 않는다.
-- ==================================================================

alter table member add (tokens_valid_after timestamp);
